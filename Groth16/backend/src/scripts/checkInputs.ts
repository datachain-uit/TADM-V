import fs from 'fs';
import path from 'path';

const PROJECT_ROOT = path.resolve(__dirname, '../../..');

const CODE_ROOT = path.resolve(PROJECT_ROOT, '..');

const SCENARIOS = [1, 10, 30, 60, 100, 500];

const ADV_DATA_PATH = 'Mode A/experiments/data';

const ONC_DATA_PATH = 'Mode B/experiments/data';

const G16_DATA_PATH = 'Groth16/experiments/data';

function readJson(p: string): any {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

type Triple = {
  student_id: string;
  amount: string;
  rho: string;
};

function triplesFromDataset(d: any): Triple[] {
  const records: any[] = d.students ?? [];

  return records.map((r: any) => ({
    student_id: String(r.student_id),
    amount: String(r.amount),
    rho: String(r.note?.rho ?? ''),
  }));
}

function triplesFromInputs(d: any): Triple[] {
  const records: any[] = d.inputs ?? [];

  return records.map((r: any) => ({
    student_id: String(r.input?.student_id ?? ''),
    amount: String(r.input?.amount ?? ''),
    rho: String(r.input?.rho ?? ''),
  }));
}

function compareTriples(a: Triple[], b: Triple[]): { matches: boolean; mismatchCount: number; example: string } {
  if (a.length !== b.length) {
    return {
      matches: false,
      mismatchCount: Math.abs(a.length - b.length),
      example: 'record count differs: ' + a.length + ' vs ' + b.length,
    };
  }

  let mismatches = 0;
  let example = '';

  for (let i = 0; i < a.length; i++) {
    const x = a[i];
    const y = b[i];

    if (x === undefined || y === undefined) {
      mismatches++;
      continue;
    }

    if (x.student_id !== y.student_id || x.amount !== y.amount || x.rho !== y.rho) {
      mismatches++;

      if (example === '') {
        example = 'record #' + i + ': ' + JSON.stringify(x) + ' vs ' + JSON.stringify(y);
      }
    }
  }

  return {
    matches: mismatches === 0,
    mismatchCount: mismatches,
    example: example,
  };
}

function main() {
  const results: any[] = [];

  for (const n of SCENARIOS) {
    const pAdv = path.resolve(CODE_ROOT, ADV_DATA_PATH, 'dataset_n' + n + '.json');

    const pOnc = path.resolve(CODE_ROOT, ONC_DATA_PATH, 'dataset_n' + n + '.json');

    const pG16 = path.resolve(CODE_ROOT, G16_DATA_PATH, 'inputs_n' + n + '.json');

    const present = {
      adv: fs.existsSync(pAdv),
      onc: fs.existsSync(pOnc),
      g16: fs.existsSync(pG16),
    };

    if (!present.adv || !present.onc || !present.g16) {
      results.push({
        n,
        missing: Object.keys(present).filter((k: string) => !(present as any)[k]),
      });

      continue;
    }

    const dAdv = readJson(pAdv);
    const dOnc = readJson(pOnc);
    const dG16 = readJson(pG16);

    const tAdv = triplesFromDataset(dAdv);
    const tOnc = triplesFromDataset(dOnc);
    const tG16 = triplesFromInputs(dG16);

    const source = String(dG16.nguon_dataset ?? '(not recorded)');

    const pointsToOnc =
      source.replace(/\\/g, '/').indexOf('zk-halo2-onchain') !== -1 || source.indexOf('Mode B') !== -1;

    results.push({
      n,
      recordCount: {
        adv: tAdv.length,
        onc: tOnc.length,
        g16: tG16.length,
      },
      depth: {
        adv: dAdv.merkle_depth,
        onc: dOnc.merkle_depth,
        g16: dG16.merkle_depth,
      },
      advVsOnc: compareTriples(tAdv, tOnc),
      oncVsG16: compareTriples(tOnc, tG16),
      source,
      pointsToOnc,
    });
  }

  if (process.argv.indexOf('--json') !== -1) {
    console.log(JSON.stringify(results, null, 2));
    return;
  }

  console.log('# Input check across the three branches');
  console.log('');
  console.log('> Generated by `npm run check-inputs`. Only READS the other two repositories.');
  console.log('> Compares by **the triple `(student_id, amount, rho)`** - what actually goes into the circuit.');
  console.log(
    '> ⚠️ Does **not** compare raw SHA-256: ADV uses CRLF, ONC uses LF, so the raw hashes differ' +
      ' on all seven files even though the content is identical.',
  );
  console.log('');
  console.log('| n | records | `d` | ADV ↔ ONC | ONC ↔ G16 | G16 reads ONC directly |');
  console.log('|---:|---:|---:|---|---|---|');

  let total = 0;
  let passed = true;

  for (const r of results) {
    if (r.missing) {
      passed = false;
      console.log('| ' + r.n + ' | — | — | — | — | 🔴 missing: ' + r.missing.join(', ') + ' |');
      continue;
    }

    total += r.recordCount.onc;

    const depthOk = r.depth.adv === r.depth.onc && r.depth.onc === r.depth.g16;

    if (!r.advVsOnc.matches || !r.oncVsG16.matches || !r.pointsToOnc || !depthOk) {
      passed = false;
    }

    console.log(
      '| ' +
        r.n +
        ' | ' +
        r.recordCount.onc +
        ' | ' +
        (depthOk ? r.depth.onc : '🔴 ' + JSON.stringify(r.depth)) +
        ' | ' +
        (r.advVsOnc.matches ? '✅' : '🔴 ' + r.advVsOnc.mismatchCount + ' mismatched') +
        ' | ' +
        (r.oncVsG16.matches ? '✅' : '🔴 ' + r.oncVsG16.mismatchCount + ' mismatched') +
        ' | ' +
        (r.pointsToOnc ? '✅' : '🔴 ' + r.source) +
        ' |',
    );
  }

  console.log('');
  console.log(
    '**Total ' +
      total +
      ' records** · ' +
      (passed
        ? '✅ **all three branches share the same input** - the sentence *"same input"* may be used.'
        : '🔴 **MISMATCH** - do not write *"same input"* in the paper yet.'),
  );

  if (!passed) {
    console.log('');
    console.log('Details of the first mismatch:');

    for (const r of results) {
      if (r.advVsOnc && !r.advVsOnc.matches) {
        console.log('- n=' + r.n + ' ADV↔ONC: ' + r.advVsOnc.example);
      }
      if (r.oncVsG16 && !r.oncVsG16.matches) {
        console.log('- n=' + r.n + ' ONC↔G16: ' + r.oncVsG16.example);
      }
    }
  }

  console.log('');
  console.log(
    '📌 The **ONC ↔ G16** link is the most suspect one: if `prepareInputs.ts`' +
      ' accidentally **regenerates** `rho` instead of reading it, every number still runs normally and' +
      ' only the sentence *"same input"* becomes false. No other check catches that.',
  );

  if (!passed) {
    process.exitCode = 1;
  }
}

main();
