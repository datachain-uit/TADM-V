import fs from 'fs';
import path from 'path';

const PROJECT_ROOT = path.resolve(__dirname, '../../..');

const CODE_ROOT = path.resolve(PROJECT_ROOT, '..');

const SCENARIOS = [1, 10, 30, 60, 100, 500];

const SLOPE_THRESHOLD = 5;

const SOURCES: { name: string; path: string }[] = [
  {
    name: 'ADV',
    path: 'Mode A/experiments/results/quantitative/gas_offchain_raw.csv',
  },
  {
    name: 'ONC',
    path: 'Mode B/experiments/results/quantitative/gas_onchain_raw.csv',
  },
  {
    name: 'G16',
    path: 'Groth16/experiments/results/quantitative/gas_groth16_raw.csv',
  },
];

function readCsv(p: string): Record<string, string>[] {
  const raw = fs.readFileSync(p, 'utf8').trim().split(/\r?\n/);

  const headerLine = raw[0];

  if (headerLine === undefined) {
    throw new Error('Empty file: ' + p);
  }

  const columns = headerLine.split(',');

  return raw.slice(1).map((line: string) => {
    const o: Record<string, string> = {};
    const v = line.split(',');
    columns.forEach((c: string, i: number) => {
      o[c] = v[i] ?? '';
    });
    return o;
  });
}

function mean(rows: Record<string, string>[], column: string): number | null {
  const v = rows
    .map((r) => r[column])
    .filter((x): x is string => x !== undefined && x.trim() !== '')
    .map(Number)
    .filter((x: number) => Number.isFinite(x));

  if (v.length === 0) {
    return null;
  }

  return v.reduce((a: number, b: number) => a + b, 0) / v.length;
}

function formatNumber(x: number | null): string {
  if (x === null) {
    return '—';
  }

  return Math.round(x)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

function ratio(a: number | null, b: number | null): string {
  if (a === null || b === null || b === 0) {
    return '—';
  }

  return (a / b).toFixed(2) + '×';
}

function main() {
  const d: any = {};
  const missing: string[] = [];

  for (const source of SOURCES) {
    const p = path.resolve(CODE_ROOT, source.path);

    if (!fs.existsSync(p)) {
      missing.push(source.name);
      continue;
    }

    const rows = readCsv(p);

    const updateRootValues = rows
      .map((r) => r['update_root_gas'])
      .filter((x): x is string => x !== undefined && x.trim() !== '')
      .map(Number)
      .filter((x: number) => Number.isFinite(x));

    const updateRootByN: Record<string, number> = {};

    for (const scenario of SCENARIOS) {
      const values = rows
        .filter((r) => Number(r['n']) === scenario)
        .map((r) => Number(r['update_root_gas']))
        .filter((x: number) => Number.isFinite(x));

      if (values.length > 0) {
        updateRootByN[String(scenario)] = values.reduce((a: number, b: number) => a + b, 0) / values.length;
      }
    }

    d[source.name] = {
      sampleCount: rows.length,
      update_root_min: updateRootValues.length > 0 ? Math.min(...updateRootValues) : null,
      update_root_max: updateRootValues.length > 0 ? Math.max(...updateRootValues) : null,
      update_root_by_n: updateRootByN,
      deploy_pool_gas: mean(rows, 'deploy_pool_gas'),
      deploy_verifier_gas: mean(rows, 'deploy_verifier_gas'),
      update_root_gas: mean(rows, 'update_root_gas'),
      verify_gas: mean(rows, 'verify_gas'),
      withdraw_gas: mean(rows, 'withdraw_gas'),
      verify_record_gas: mean(rows, 'verify_record_gas'),
      settle_gas: mean(rows, 'settle_gas'),
    };
  }

  if (process.argv.indexOf('--json') !== -1) {
    console.log(JSON.stringify({ data: d, missing }, null, 2));
    return;
  }

  console.log('# Three-branch comparison - gas');
  console.log('');
  console.log('> Generated by `npm run compare`. **No number is typed by hand.**');
  console.log('> Only READS the CSVs of the other two branches, changes nothing there.');

  if (missing.length > 0) {
    console.log('> ⚠️ Missing data: **' + missing.join(', ') + '** - not run yet or not finalised.');
  }

  console.log('');
  console.log('| | ADV | ONC | G16 |');
  console.log('|---|---:|---:|---:|');
  console.log(
    '| samples | ' +
      ['ADV', 'ONC', 'G16'].map((t: string) => (d[t] ? String(d[t].sampleCount) : '—')).join(' | ') +
      ' |',
  );

  const row = (title: string, key: string) => {
    console.log(
      '| `' +
        title +
        '` | ' +
        ['ADV', 'ONC', 'G16'].map((t: string) => (d[t] ? formatNumber(d[t][key]) : '—')).join(' | ') +
        ' |',
    );
  };

  row('deploy_pool_gas', 'deploy_pool_gas');
  row('deploy_verifier_gas', 'deploy_verifier_gas');
  console.log(
    '| `update_root_gas` | ' +
      ['ADV', 'ONC', 'G16']
        .map((t: string) => {
          if (!d[t]) {
            return '—';
          }

          const mn = d[t].update_root_min;
          const mx = d[t].update_root_max;

          if (mn === null || mx === null) {
            return '—';
          }

          if (mx - mn > mn * 0.01) {
            return formatNumber(mn) + ' → ' + formatNumber(mx) + ' *(by `n`)*';
          }

          return formatNumber(d[t].update_root_gas);
        })
        .join(' | ') +
      ' |',
  );
  row('verify_gas', 'verify_gas');
  row('withdraw_gas', 'withdraw_gas');
  row('verify_record_gas', 'verify_record_gas');
  row('settle_gas', 'settle_gas');

  console.log('');
  console.log('## Correct comparison pairs - by BUSINESS STEP');
  console.log('');
  console.log('| Step | ADV | ONC | G16 | ONC/ADV | G16/ADV |');
  console.log('|---|---:|---:|---:|---:|---:|');

  const advPayout = d['ADV'] ? d['ADV'].withdraw_gas : null;
  const oncPayout = d['ONC'] ? d['ONC'].settle_gas : null;
  const g16Payout = d['G16'] ? d['G16'].settle_gas : null;

  console.log(
    '| **Payout** | ' +
      formatNumber(advPayout) +
      ' | ' +
      formatNumber(oncPayout) +
      ' | ' +
      formatNumber(g16Payout) +
      ' | ' +
      ratio(oncPayout, advPayout) +
      ' | ' +
      ratio(g16Payout, advPayout) +
      ' |',
  );

  const oncVerify = d['ONC'] ? d['ONC'].verify_record_gas : null;
  const g16Verify = d['G16'] ? d['G16'].verify_record_gas : null;

  console.log(
    '| **Verification** | *(no mechanism)* | ' +
      formatNumber(oncVerify) +
      ' | ' +
      formatNumber(g16Verify) +
      ' | ' +
      ratio(oncVerify, advPayout) +
      ' | ' +
      ratio(g16Verify, advPayout) +
      ' |',
  );

  console.log('');
  console.log(
    '⛔ **Do not use `ONC withdraw_gas / ADV withdraw_gas`** - that folds the payout cost' +
      ' into the verification cost. The old `×7.9` ratio came from that folding and was rejected.',
  );
  console.log('');
  console.log(
    '📌 ADV `verify_gas` and `deploy_verifier_gas` are **left EMPTY**, not `0` -' +
      ' the mechanism does not exist, it is not free.',
  );
  console.log('');
  console.log(
    '📌 **`update_root_gas` now GROWS WITH `n` on ALL THREE BRANCHES** *(K19 sync,' +
      ' 2026-09-09)*. All three publish the commitment array on chain (V4), ~773 gas' +
      ' per leaf. Before K19, ONC and G16 passed an **empty** array, so this column stayed flat and' +
      ' **measured something different from ADV** - ONC itself recorded that at the time *"K1 lost its' +
      ' meaning"*.',
  );
  console.log('');
  console.log(
    '🔴 **Therefore K1 can NO LONGER compare absolute values.** The three branches use three different' +
      ' hash functions ⇒ three different commitment sets ⇒ different numbers of `0` bytes in calldata.' +
      ' Each `0` byte is 12 gas cheaper, and at `n = 500` there are ~16 000 bytes, so differences' +
      ' of hundreds of gas are **normal, not a bug**.',
  );
  console.log(
    '   ⇒ The invariant quantity is the **SLOPE - gas per leaf**. It says all three branches publish' +
      ' **the same amount of data per commitment**, which is what K1 needs to' +
      ' establish. Threshold: **' +
      SLOPE_THRESHOLD +
      ' gas/leaf**.',
  );

  console.log('');
  console.log('## Cross-checks');
  console.log('');
  console.log('| Check | Expected | Result |');
  console.log('|---|---|---|');

  const slopeOf = (t: string): { slope: number; from: number; to: number } | null => {
    if (!d[t] || !d[t].update_root_by_n) {
      return null;
    }

    const present = Object.keys(d[t].update_root_by_n)
      .map(Number)
      .sort((a: number, b: number) => a - b);

    const from = present[0];
    const to = present[present.length - 1];

    if (from === undefined || to === undefined || to === from) {
      return null;
    }

    return {
      slope: (d[t].update_root_by_n[String(to)] - d[t].update_root_by_n[String(from)]) / (to - from),
      from,
      to,
    };
  };

  const slopes = ['ADV', 'ONC', 'G16']
    .map((t: string) => ({ name: t, result: slopeOf(t) }))
    .filter((x): x is { name: string; result: { slope: number; from: number; to: number } } => x.result !== null);

  if (slopes.length >= 2) {
    const values = slopes.map((x) => x.result.slope);

    const difference = Math.max(...values) - Math.min(...values);

    console.log(
      '| **K1** `update_root_gas` slope *(gas per leaf)* | branches differ by ≤ ' +
        SLOPE_THRESHOLD +
        ' gas/leaf | ' +
        (difference <= SLOPE_THRESHOLD ? '✅' : '🔴') +
        ' ' +
        slopes.map((x) => x.name + ' **' + x.result.slope.toFixed(1) + '**').join(' · ') +
        ' *(difference ' +
        difference.toFixed(1) +
        ')* |',
    );
  } else {
    console.log(
      '| **K1** `update_root_gas` slope | branches differ by ≤ ' +
        SLOPE_THRESHOLD +
        ' gas/leaf | ⬜ not enough data *(needs ≥ 2 scenarios' +
        ' on ≥ 2 branches)* |',
    );
  }

  if (d['ONC'] && d['G16']) {
    const meanDifference = Math.abs(d['ONC'].update_root_gas - d['G16'].update_root_gas);

    console.log(
      '| *(reference)* mean `update_root_gas` difference ONC ↔ G16 |' +
        ' **not a check** - see the K1 slope | ⬜ differs by ' +
        formatNumber(meanDifference) +
        ' gas |',
    );

    const gapOnc = d['ONC'].verify_record_gas + d['ONC'].settle_gas - d['ONC'].withdraw_gas;

    const gapG16 = d['G16'].verify_record_gas + d['G16'].settle_gas - d['G16'].withdraw_gas;

    const difference = Math.abs(gapOnc - gapG16);

    console.log(
      '| **Cost of splitting into two phases** | roughly equal - it is the second transaction fee' +
        ' + writing `Claim`, independent of the proof system | ' +
        (difference < 20000 ? '✅' : '🔴') +
        ' ONC **+' +
        formatNumber(gapOnc) +
        '** · G16 **+' +
        formatNumber(gapG16) +
        '** (difference ' +
        formatNumber(difference) +
        ') |',
    );
  }
}

main();
