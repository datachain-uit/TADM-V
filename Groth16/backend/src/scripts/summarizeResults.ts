import fs from 'fs';
import path from 'path';

const PROJECT_ROOT = path.resolve(__dirname, '../../..');

const RESULT_DIR = path.resolve(PROJECT_ROOT, 'experiments/results/quantitative');

const SCENARIOS = [1, 10, 30, 60, 100, 500];

const GAS_COLUMNS = [
  'deploy_pool_gas',
  'deploy_verifier_gas',
  'update_root_gas',
  'verify_gas',
  'withdraw_gas',
  'verify_record_gas',
  'settle_gas',
];

const MS_COLUMNS = ['verify_onchain_ms', 'withdraw_ms', 'verify_record_ms', 'settle_ms'];

const PERF_COLUMNS = [
  'witness_ms',
  'setup_ms',
  'prove_ms',
  'proof_generation_ms',
  'verify_native_ms',
  'proof_bytes',
  'calldata_bytes',
];

function readCsv(p: string): Record<string, string>[] {
  const raw = fs.readFileSync(p, 'utf8').trim().split(/\r?\n/);

  const headerLine = raw[0];

  if (headerLine === undefined) {
    throw new Error('Empty file: ' + p);
  }

  const columns = headerLine.split(',');

  return raw.slice(1).map((line: string) => {
    const o: Record<string, string> = {};
    const v = line.split(',');

    columns.forEach((c: string, i: number) => {
      o[c] = v[i] ?? '';
    });

    return o;
  });
}

type Stats = {
  n: number;
  mean: number;
  min: number;
  max: number;
  sigma: number;
};

function computeStats(v: number[]): Stats | null {
  if (v.length === 0) {
    return null;
  }

  const mean = v.reduce((a: number, b: number) => a + b, 0) / v.length;

  const sigma = Math.sqrt(v.reduce((a: number, b: number) => a + (b - mean) * (b - mean), 0) / v.length);

  return {
    n: v.length,
    mean,
    min: Math.min(...v),
    max: Math.max(...v),
    sigma,
  };
}

function pick(rows: Record<string, string>[], column: string): number[] {
  return rows
    .map((r) => r[column])
    .filter((x): x is string => x !== undefined && x.trim() !== '')
    .map(Number)
    .filter((x: number) => Number.isFinite(x));
}

function formatNumber(x: number, decimals: number): string {
  const s = x.toFixed(decimals);

  const parts = s.split('.');

  const integerPart = parts[0] ?? '0';

  const grouped = integerPart.replace(/\B(?=(\d{3})+(?!\d))/g, ',');

  return parts.length > 1 ? grouped + '.' + parts[1] : grouped;
}

function main() {
  const gasPath = path.resolve(RESULT_DIR, 'gas_groth16_raw.csv');

  if (!fs.existsSync(gasPath)) {
    throw new Error('Missing ' + gasPath + ' - experiment:gas has not been run.');
  }

  const gas = readCsv(gasPath);

  const byN: any = {};

  for (const n of SCENARIOS) {
    const gasRows = gas.filter((r) => Number(r['n']) === n);

    if (gasRows.length === 0) {
      continue;
    }

    const entry: any = {
      n,
      sampleCount: gasRows.length,
    };

    for (const c of GAS_COLUMNS.concat(MS_COLUMNS)) {
      entry[c] = computeStats(pick(gasRows, c));
    }

    const perfPath = path.resolve(RESULT_DIR, 'performance_groth16_n' + n + '.csv');

    if (fs.existsSync(perfPath)) {
      const perfRows = readCsv(perfPath);

      for (const c of PERF_COLUMNS) {
        entry[c] = computeStats(pick(perfRows, c));
      }
    }

    byN[n] = entry;
  }

  if (process.argv.indexOf('--json') !== -1) {
    console.log(JSON.stringify(byN, null, 2));
    return;
  }

  const present = Object.keys(byN).map(Number);

  const totalSamples = present.reduce((a: number, n: number) => a + byN[n].sampleCount, 0);

  console.log('# Quantitative summary - Groth16 baseline');
  console.log('');
  console.log('> Generated by `npm run summary` from `experiments/results/quantitative/`.');
  console.log('> **No number in this file is typed by hand.** Re-running the command gives the same output.');
  console.log(
    '> Total **' +
      formatNumber(totalSamples, 0) +
      '** samples · ' +
      present.length +
      ' scenarios · arithmetic mean, with N and σ.',
  );
  console.log('');

  const table = (title: string, columns: string[], decimals: number) => {
    console.log('## ' + title);
    console.log('');
    console.log('| n | samples | ' + columns.join(' | ') + ' |');
    console.log('|---:|---:|' + columns.map(() => '---:').join('|') + '|');

    for (const n of present) {
      const m = byN[n];
      const o = columns.map((c: string) => (m[c] ? formatNumber(m[c].mean, decimals) : '—'));
      console.log('| ' + n + ' | ' + m.sampleCount + ' | ' + o.join(' | ') + ' |');
    }
    console.log('');
  };

  table('Gas', GAS_COLUMNS, 0);
  table('On-chain time (ms)', MS_COLUMNS, 1);
  table('Proof generation time (ms) and sizes', PERF_COLUMNS, 1);

  console.log('## Self-checks');
  console.log('');
  console.log('| Check | Threshold | Result |');
  console.log('|---|---|---|');

  let k2 = true;
  const ranges: string[] = [];

  for (const n of present) {
    const s = byN[n]['settle_gas'];
    if (s) {
      const range = s.max - s.min;
      if (range >= 1000) {
        k2 = false;
      }
      ranges.push(String(range));
    }
  }

  console.log(
    '| **K2** `settle_gas` range within one scenario | < 1 000 gas | ' +
      (k2 ? '✅' : '🔴') +
      ' ' +
      ranges.join(' · ') +
      ' |',
  );

  const means = present
    .map((n: number) => byN[n]['settle_gas'])
    .filter((x: Stats | null): x is Stats => x !== null && x !== undefined)
    .map((x: Stats) => x.mean);

  if (means.length > 0) {
    const overallMean = means.reduce((a: number, b: number) => a + b, 0) / means.length;

    const spread = (Math.max(...means) - Math.min(...means)) / overallMean;

    console.log(
      '| **K3** mean `settle_gas` flat across ' +
        means.length +
        ' scenarios | spread < 1 % | ' +
        (spread < 0.01 ? '✅' : '🔴') +
        ' ' +
        (spread * 100).toFixed(3) +
        ' % |',
    );
  }

  console.log('');
  console.log(
    '📌 **K1** *(compare `update_root_gas` with ADV/ONC)* must be cross-checked by hand - ' +
      'it needs the numbers of the other two branches.',
  );
  console.log('');
  console.log('📌 Every number above is an **arithmetic mean**. For min/max/σ run ' + '`npm run summary -- --json`.');
}

main();
